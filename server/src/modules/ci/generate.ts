/**
 * ci — pure file generators (ring 2). No I/O: agent + memory + options in,
 * `CiFile[]` out. Untrusted text (prompt, skill bodies, memory) is always
 * written as data through the YAML/JSON serializers, never concatenated.
 */
import { stringify } from 'yaml';
import {
  AgentManifest,
  CI_TEMPLATE_VERSION,
  type CiFile,
  type CiPostAs,
  type CiTrigger,
} from '@devdigest/shared';
import {
  ARTIFACT_FILE,
  ARTIFACT_NAME,
  MANIFEST_DIR,
  MEMORY_MAX_BYTES,
  MEMORY_MAX_ITEMS,
  MEMORY_PATH,
  NODE_VERSION,
  RUNNER_PATH,
  SKILLS_DIR,
  WORKFLOW_PATH,
} from './constants.js';
import { looksLikeSecret, slugify, uniqueSlugs } from './helpers.js';
import type { ExportAgent, ExportSkill, MemoryRow } from './ports.js';

export const agentSlug = (agent: Pick<ExportAgent, 'name'>): string => slugify(agent.name) || 'agent';

export const manifestPath = (agent: Pick<ExportAgent, 'name'>): string =>
  `${MANIFEST_DIR}/${agentSlug(agent)}.yaml`;

export function buildManifest(agent: ExportAgent, skillSlugs: string[]): string {
  const manifest = AgentManifest.parse({
    name: agent.name,
    provider: agent.provider,
    model: agent.model,
    system_prompt: agent.systemPrompt,
    skills: skillSlugs,
    strategy: agent.strategy,
    ci_fail_on: agent.ciFailOn,
  });
  // Exactly the seven AgentManifest fields, in a stable order.
  return stringify(
    {
      name: manifest.name,
      provider: manifest.provider,
      model: manifest.model,
      system_prompt: manifest.system_prompt,
      skills: manifest.skills,
      strategy: manifest.strategy,
      ci_fail_on: manifest.ci_fail_on,
    },
    { lineWidth: 0 },
  );
}

export function buildSkillFiles(skills: ExportSkill[]): { slugs: string[]; files: CiFile[] } {
  const slugs = uniqueSlugs(skills.map((s) => s.name));
  const files = skills.map((s, i) => ({
    path: `${SKILLS_DIR}/${slugs[i]}.md`,
    contents: s.body.endsWith('\n') ? s.body : `${s.body}\n`,
    editable: false,
  }));
  return { slugs, files };
}

export interface MemoryFile {
  contents: string;
  included: number;
  /** Rows eligible for export (rows that look like secrets are not). */
  total: number;
  /** Rows left out because their content looks like an API key. */
  dropped: number;
}

/** Newest first (rows arrive that way); stops at the first row that would pass a cap. */
export function buildMemoryJsonl(allRows: MemoryRow[]): MemoryFile {
  // Memory is committed to a repo (maybe public): never export key-like content.
  const rows = allRows.filter((r) => !looksLikeSecret(r.content));
  const dropped = allRows.length - rows.length;
  const lines: string[] = [];
  let bytes = 0;
  for (const r of rows) {
    if (lines.length >= MEMORY_MAX_ITEMS) break;
    const line = JSON.stringify({ id: r.id, scope: r.scope, kind: r.kind, content: r.content });
    const size = Buffer.byteLength(line, 'utf8') + 1;
    if (bytes + size > MEMORY_MAX_BYTES) break;
    lines.push(line);
    bytes += size;
  }
  return {
    contents: lines.length ? `${lines.join('\n')}\n` : '',
    included: lines.length,
    total: rows.length,
    dropped,
  };
}

export interface WorkflowOptions {
  postAs: CiPostAs;
  triggers: CiTrigger[];
  agentSlug: string;
}

export function buildWorkflow(opts: WorkflowOptions): string {
  const writes = opts.postAs !== 'none';
  const doc = {
    name: 'DevDigest review',
    on: { pull_request: { types: opts.triggers } },
    permissions: { contents: 'read', 'pull-requests': writes ? 'write' : 'read' },
    concurrency: {
      group: 'devdigest-review-${{ github.event.pull_request.number }}',
      'cancel-in-progress': true,
    },
    jobs: {
      review: {
        'runs-on': 'ubuntu-latest',
        steps: [
          { uses: 'actions/checkout@v4' },
          { uses: 'actions/setup-node@v4', with: { 'node-version': NODE_VERSION } },
          {
            name: 'Run DevDigest review',
            run: `node ${RUNNER_PATH}`,
            env: {
              OPENROUTER_API_KEY: '${{ secrets.OPENROUTER_API_KEY }}',
              GITHUB_TOKEN: '${{ secrets.GITHUB_TOKEN }}',
              DEVDIGEST_AGENT: `${MANIFEST_DIR}/${opts.agentSlug}.yaml`,
              DEVDIGEST_POST_AS: opts.postAs,
            },
          },
          {
            uses: 'actions/upload-artifact@v4',
            if: 'always()',
            with: { name: ARTIFACT_NAME, path: ARTIFACT_FILE, 'if-no-files-found': 'ignore' },
          },
        ],
      },
    },
  };
  return `# ${CI_TEMPLATE_VERSION} · generated by DevDigest · editable\n${stringify(doc, { lineWidth: 0 })}`;
}

export interface BuiltFiles {
  files: CiFile[];
  memory: { included: number; total: number; dropped: number };
}

/** All files in AC-6 order: manifest, skills, memory, runner, workflow. */
export function buildFiles(input: {
  agent: ExportAgent;
  memoryRows: MemoryRow[];
  runnerBundle: string;
  postAs: CiPostAs;
  triggers: CiTrigger[];
}): BuiltFiles {
  const { slugs, files: skillFiles } = buildSkillFiles(input.agent.skills);
  const memory = buildMemoryJsonl(input.memoryRows);
  const files: CiFile[] = [
    { path: manifestPath(input.agent), contents: buildManifest(input.agent, slugs), editable: false },
    ...skillFiles,
    { path: MEMORY_PATH, contents: memory.contents, editable: false },
    { path: RUNNER_PATH, contents: input.runnerBundle, editable: false },
    {
      path: WORKFLOW_PATH,
      contents: buildWorkflow({
        postAs: input.postAs,
        triggers: input.triggers,
        agentSlug: agentSlug(input.agent),
      }),
      editable: true,
    },
  ];
  return { files, memory: { included: memory.included, total: memory.total, dropped: memory.dropped } };
}
