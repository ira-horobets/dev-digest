import { describe, it, expect, afterEach, beforeEach, vi } from "vitest";
import { render, screen, cleanup, fireEvent, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { NextIntlClientProvider } from "next-intl";
import type { Agent } from "@devdigest/shared";
import ciMessages from "../../../../../../messages/en/ci.json";

const WORKFLOW = ".github/workflows/devdigest-review.yml";
const GENERATED = "# devdigest-ci/v1 · generated by DevDigest · editable\non:\n  pull_request:\n    types: [opened, synchronize]\n";

const previewState = {
  workflow_state: "absent" as "absent" | "foreign",
  studio_token: true,
  repo_public: false as boolean | null,
  dropped: 0,
};
const previewInputs: unknown[] = [];

vi.mock("@/lib/hooks/core", () => ({
  useRepos: () => ({ data: [{ id: "r1", full_name: "acme/api" }, { id: "r2", full_name: "acme/web" }] }),
}));

const exportMutate = vi.fn();
vi.mock("@/lib/hooks/ci", () => ({
  useCiPreview: (_id: string, input: unknown, enabled: boolean) => {
    previewInputs.push(input);
    if (!enabled) return { data: undefined, isLoading: false, isError: false };
    return {
      isLoading: false,
      isError: false,
      data: {
        files: [
          { path: ".devdigest/agents/security-reviewer.yaml", contents: "name: Security Reviewer\n", editable: false },
          { path: ".devdigest/memory.jsonl", contents: "", editable: false },
          { path: ".devdigest/runner/index.js", contents: "// runner", editable: false },
          { path: WORKFLOW, contents: GENERATED, editable: true },
        ],
        template_version: "devdigest-ci/v1",
        memory: { included: 3, total: 5, dropped: previewState.dropped },
        repo_public: previewState.repo_public,
        workflow_state: previewState.workflow_state,
        studio_token: previewState.studio_token,
      },
    };
  },
  useCiSecrets: () => ({
    isLoading: false,
    data: {
      studio_token: true,
      secrets: [
        { name: "GITHUB_TOKEN", state: "ready", reason: null },
        { name: "OPENROUTER_API_KEY", state: "unknown", reason: "Environment secrets cannot be listed" },
      ],
    },
  }),
  useExportCi: () => ({ mutateAsync: exportMutate, isPending: false }),
}));

const download = vi.fn();
vi.mock("@/lib/download", () => ({ downloadBlob: (...a: unknown[]) => download(...a) }));

import { ExportCiWizard } from "./ExportCiWizard";

const AGENT: Agent = {
  id: "ag1",
  name: "Security Reviewer",
  description: "",
  provider: "openrouter",
  model: "deepseek/deepseek-v4-flash",
  system_prompt: "p",
  output_schema: null,
  strategy: "single-pass",
  ci_fail_on: "critical",
  repo_intel: true,
  skill_count: 0,
  stats: { runs: 4, accept_rate: 0.5, avg_cost_usd: 0.012 },
  enabled: true,
  version: 1,
};

function renderWizard(agent: Agent = AGENT, onClose = vi.fn()) {
  render(
    <NextIntlClientProvider locale="en" messages={{ ci: ciMessages }}>
      <ExportCiWizard agent={agent} onClose={onClose} />
    </NextIntlClientProvider>,
  );
  return onClose;
}

beforeEach(() => {
  previewState.workflow_state = "absent";
  previewState.studio_token = true;
  previewState.repo_public = false;
  previewState.dropped = 0;
  previewInputs.length = 0;
  exportMutate.mockReset();
  download.mockReset();
});
afterEach(cleanup);

async function toPreview(user: ReturnType<typeof userEvent.setup>) {
  await user.selectOptions(screen.getByLabelText("Target repository"), "acme/api");
  await user.click(screen.getByRole("button", { name: "Continue" }));
}

describe("ExportCiWizard", () => {
  it("walks Target → Preview → Configure → Install and opens a PR with the chosen options", async () => {
    const user = userEvent.setup();
    exportMutate.mockResolvedValue({ pr_url: "https://github.com/acme/api/pull/9" });
    renderWizard();

    // Step 1: GitHub Actions is pre-selected and recommended; Continue needs a repo.
    expect(screen.getByRole("dialog")).toHaveTextContent("Export to CI");
    expect(screen.getByRole("radio", { name: /GitHub Actions/ })).toBeChecked();
    expect(screen.getByText("recommended")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Continue" })).toBeDisabled();
    expect(within(screen.getByRole("list", { name: "Export steps" })).getAllByRole("listitem")).toHaveLength(4);
    await user.selectOptions(screen.getByLabelText("Target repository"), "acme/api");
    await user.click(screen.getByRole("button", { name: "Continue" }));

    // Step 2: files; only the workflow is editable.
    expect(screen.getByText("Files to create")).toBeInTheDocument();
    expect(screen.getByText(".devdigest/memory.jsonl")).toBeInTheDocument();
    expect(screen.getByText(/used by CI reviews only · 3 of 5 items/)).toBeInTheDocument();
    expect(screen.getAllByText("read-only")).toHaveLength(3);
    expect(screen.getAllByText("editable")).toHaveLength(1);
    await user.click(screen.getByRole("button", { name: "Continue" }));

    // Step 3: defaults, secrets, review hint, cost.
    expect(screen.getByRole("checkbox", { name: "pull_request:opened" })).toBeChecked();
    expect(screen.getByRole("checkbox", { name: "pull_request:synchronize" })).toBeChecked();
    expect(screen.getByRole("checkbox", { name: "pull_request:reopened" })).not.toBeChecked();
    expect(screen.getByRole("radio", { name: /GitHub review/ })).toBeChecked();
    expect(screen.getByText(/Your repo's Actions settings may reject reviews/)).toBeInTheDocument();
    expect(screen.getByText("Add these to your repo's Actions secrets before the workflow runs.")).toBeInTheDocument();
    expect(screen.getByText("GITHUB_TOKEN")).toBeInTheDocument();
    expect(screen.getByText("ready")).toBeInTheDocument();
    expect(screen.getByText("unknown")).toBeInTheDocument();
    expect(screen.getByText(/billed to the repo's OpenRouter key/)).toBeInTheDocument();
    expect(screen.getByText(/No GitHub App is needed/)).toBeInTheDocument();
    await user.click(screen.getByRole("radio", { name: /PR comment/ }));
    expect(screen.queryByText(/Your repo's Actions settings may reject reviews/)).not.toBeInTheDocument();
    await user.click(screen.getByRole("checkbox", { name: "pull_request:reopened" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));

    // Step 4: PR is the default and states repo + file count; docs link opens GitHub docs.
    expect(screen.getByRole("radio", { name: /Open a PR with these files/ })).toBeChecked();
    expect(screen.getByText(/pull request in acme\/api|PR in acme\/api titled/)).toBeInTheDocument();
    expect(screen.getByText(/with the 4 generated files/)).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "GitHub Action setup docs" })).toHaveAttribute(
      "href",
      expect.stringContaining("using-secrets-in-github-actions"),
    );
    await user.click(screen.getByRole("button", { name: "Install" }));

    expect(exportMutate).toHaveBeenCalledWith({
      agentId: "ag1",
      input: { repo: "acme/api", post_as: "pr_comment", triggers: ["opened", "synchronize", "reopened"], confirm_overwrite: false },
    });
    expect(await screen.findByRole("link", { name: "View pull request" })).toHaveAttribute("href", "https://github.com/acme/api/pull/9");
  });

  it("blocks a non-OpenRouter agent on the Target step and names the provider (AC-5)", async () => {
    const user = userEvent.setup();
    renderWizard({ ...AGENT, provider: "openai" });
    await user.selectOptions(screen.getByLabelText("Target repository"), "acme/api");
    expect(screen.getByRole("alert")).toHaveTextContent("This agent uses openai. CI supports OpenRouter only");
    expect(screen.getByRole("button", { name: "Continue" })).toBeDisabled();
  });

  it("invalid YAML shows the parse error and disables Install; a key-like paste warns but allows it (AC-14, AC-15)", async () => {
    const user = userEvent.setup();
    exportMutate.mockResolvedValue({ pr_url: "https://github.com/acme/api/pull/1" });
    renderWizard();
    await toPreview(user);
    const editor = screen.getByRole("textbox", { name: WORKFLOW });

    fireEvent.change(editor, { target: { value: "on: [pull_request\n" } });
    expect(screen.getByText(/Not valid YAML/)).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    expect(screen.getByRole("button", { name: "Install" })).toBeDisabled();
    await user.click(screen.getByRole("button", { name: "Back" }));
    await user.click(screen.getByRole("button", { name: "Back" }));

    fireEvent.change(screen.getByRole("textbox", { name: WORKFLOW }), {
      target: { value: "on: push\n# sk-or-v1-abcdef1234567890\n" },
    });
    expect(screen.getByText(/looks like an API key/)).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    const install = screen.getByRole("button", { name: "Install" });
    expect(install).toBeEnabled();
    await user.click(install);
    expect(exportMutate.mock.calls[0]![0].input.workflow).toBe("on: push\n# sk-or-v1-abcdef1234567890\n");
    expect(exportMutate.mock.calls[0]![0].input.confirm_secret_warning).toBe(true);
  });

  it("changing a Configure option after editing asks before discarding the edits (AC-13)", async () => {
    const user = userEvent.setup();
    renderWizard();
    await toPreview(user);
    fireEvent.change(screen.getByRole("textbox", { name: WORKFLOW }), { target: { value: "on: push\n" } });
    await user.click(screen.getByRole("button", { name: "Continue" }));

    await user.click(screen.getByRole("checkbox", { name: "pull_request:reopened" }));
    expect(screen.getByText(/discards your edits/)).toBeInTheDocument();
    expect(screen.getByRole("checkbox", { name: "pull_request:reopened" })).not.toBeChecked();
    await user.click(screen.getByRole("button", { name: "Keep my edits" }));
    expect(screen.queryByText(/discards your edits/)).not.toBeInTheDocument();
    expect(screen.getByRole("checkbox", { name: "pull_request:reopened" })).not.toBeChecked();

    await user.click(screen.getByRole("checkbox", { name: "pull_request:reopened" }));
    await user.click(screen.getByRole("button", { name: "Regenerate" }));
    expect(screen.getByRole("checkbox", { name: "pull_request:reopened" })).toBeChecked();
    await user.click(screen.getByRole("button", { name: "Back" }));
    expect(screen.getByRole("textbox", { name: WORKFLOW })).toHaveValue(GENERATED);
  });

  it("Continue stays disabled while no trigger is selected (AC-17)", async () => {
    const user = userEvent.setup();
    renderWizard();
    await toPreview(user);
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("checkbox", { name: "pull_request:opened" }));
    await user.click(screen.getByRole("checkbox", { name: "pull_request:synchronize" }));
    expect(screen.getByText("Select at least one trigger.")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Continue" })).toBeDisabled();
  });

  it("a foreign workflow is marked 'will overwrite' and needs confirmation before Install (AC-16)", async () => {
    const user = userEvent.setup();
    previewState.workflow_state = "foreign";
    exportMutate.mockResolvedValue({ pr_url: "https://github.com/acme/api/pull/2" });
    renderWizard();
    await toPreview(user);
    expect(screen.getByText("will overwrite")).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    expect(screen.getByRole("button", { name: "Install" })).toBeDisabled();
    await user.click(screen.getByRole("button", { name: "Back" }));
    await user.click(screen.getByRole("button", { name: "Back" }));
    await user.click(screen.getByRole("checkbox", { name: /existing workflow will be overwritten/ }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Install" }));
    expect(exportMutate.mock.calls[0]![0].input.confirm_overwrite).toBe(true);
  });

  it("zip install downloads the previewed files and never calls the export API (AC-34)", async () => {
    const user = userEvent.setup();
    renderWizard();
    await toPreview(user);
    fireEvent.change(screen.getByRole("textbox", { name: WORKFLOW }), { target: { value: "on: push\n" } });
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("radio", { name: /Copy files as a zip/ }));
    await user.click(screen.getByRole("button", { name: "Install" }));
    expect(exportMutate).not.toHaveBeenCalled();
    expect(download).toHaveBeenCalledTimes(1);
    expect(download.mock.calls[0]![0]).toBe("devdigest-ci.zip");
    expect(download.mock.calls[0]![2]).toBe("application/zip");
    expect(await screen.findByText("Zip downloaded.")).toBeInTheDocument();
  });

  it("without a studio GitHub token the PR option is disabled with a reason and the zip stays available (AC-32)", async () => {
    const user = userEvent.setup();
    previewState.studio_token = false;
    renderWizard();
    await toPreview(user);
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    expect(screen.getByText(/Add a GitHub token in Settings/)).toBeInTheDocument();
    expect(screen.getByRole("radio", { name: /Open a PR with these files/ })).toHaveAttribute("aria-disabled", "true");
    expect(screen.getByRole("button", { name: "Install" })).toBeDisabled();
    await user.click(screen.getByRole("radio", { name: /Copy files as a zip/ }));
    expect(screen.getByRole("button", { name: "Install" })).toBeEnabled();
  });

  it("shows GitHub's reason and the missing permission inline when the write is rejected (AC-33)", async () => {
    const user = userEvent.setup();
    const { ApiError } = await import("@/lib/api");
    exportMutate.mockRejectedValue(new ApiError("Resource not accessible", 502, "external_service_error", { status: 403, missing_permission: "Workflows: write" }));
    renderWizard();
    await toPreview(user);
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Continue" }));
    await user.click(screen.getByRole("button", { name: "Install" }));
    await waitFor(() => expect(screen.getByText("GitHub rejected the write")).toBeInTheDocument());
    expect(screen.getByText("Resource not accessible")).toBeInTheDocument();
    expect(screen.getByText("Missing token permission: Workflows: write")).toBeInTheDocument();
    expect(screen.queryByRole("link", { name: "View pull request" })).not.toBeInTheDocument();
  });

  it("warns when the repo is public and when memory rows were left out as key-like", async () => {
    const user = userEvent.setup();
    previewState.repo_public = true;
    previewState.dropped = 2;
    renderWizard();
    await toPreview(user);
    expect(screen.getByText(/This repository is public: the memory file is committed to it/)).toBeInTheDocument();
    expect(screen.getByText(/2 memory items were left out because they look like API keys/)).toBeInTheDocument();
  });

  it("shows no public-repo warning for a private repo", async () => {
    const user = userEvent.setup();
    renderWizard();
    await toPreview(user);
    expect(screen.queryByText(/This repository is public/)).not.toBeInTheDocument();
  });

  it("Escape closes the wizard", async () => {
    const user = userEvent.setup();
    const onClose = renderWizard();
    await user.keyboard("{Escape}");
    expect(onClose).toHaveBeenCalled();
  });
});
